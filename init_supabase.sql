create table public.users (
  id uuid not null default gen_random_uuid (),
  name text null,
  email text null,
  phone text null,
  created_at timestamp with time zone not null default now(),
  constraint user_pkey primary key (id)
) TABLESPACE pg_default;

create table public.contact_messages (
  id bigint generated by default as identity not null,
  message text not null,
  -- 'form' = contact page, 'chat_lead' = submit_lead tool
  source text not null default 'form',
  created_at timestamp with time zone not null default now(),
  user_id uuid null default gen_random_uuid (),
  constraint contact_pkey primary key (id),
  constraint contact_messages_user_id_fkey foreign KEY (user_id) references users (id)
) TABLESPACE pg_default;

create table public.chat_messages (
  id bigint generated by default as identity not null,
  role text not null,
  content text not null,
  created_at timestamp with time zone not null default now(),
  user_id uuid not null default gen_random_uuid (),
  model text null,
  input_tokens integer null,
  output_tokens integer null,
  cached_tokens integer null,
  latency_ms integer null,
  finish_reason text null,
  feedback smallint null,
  constraint message_pkey primary key (id),
  constraint chat_messages_feedback_check check (feedback in (-1, 1))
) TABLESPACE pg_default;

create index if not exists chat_messages_user_created_idx
  on public.chat_messages (user_id, created_at);
create index if not exists chat_messages_created_idx
  on public.chat_messages (created_at);

-- Single-row table upserted by /api/health so Supabase counts real write activity
-- and doesn't pause the Free-plan project. RLS on with no policy: unreachable via
-- the public REST API, the server connects as postgres and bypasses it.
create table if not exists public.heartbeat (
  id integer not null,
  last_ping timestamp with time zone not null default now(),
  constraint heartbeat_pkey primary key (id)
) TABLESPACE pg_default;

alter table public.heartbeat enable row level security;

-- Fixed-window rate-limit counters (key = limiter prefix + salted SHA-256 of
-- the client IP). Purged after 24 h by /api/health. Same RLS note as above.
create table if not exists public.rate_limits (
  key text not null,
  window_start timestamp with time zone not null default now(),
  count integer not null default 1,
  constraint rate_limits_pkey primary key (key)
) TABLESPACE pg_default;

alter table public.rate_limits enable row level security;

-- RLS on the application tables (see db/migrations/002_enable_rls.sql).
alter table public.users enable row level security;
alter table public.chat_messages enable row level security;
alter table public.contact_messages enable row level security;
